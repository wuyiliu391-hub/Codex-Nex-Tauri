const DICT = {
  en: { ...en, ...pagesEn },
  "zh-CN": { ...zhCN, ...pagesZhCN },
  "zh-TW": { ...zhTW, ...pagesZhTW },
  ja: { ...ja, ...pagesJa },
  ko: { ...ko, ...pagesKo },
};

export function normalizeLang(code) {
  const raw = String(code || "en").trim();
  if (DICT[raw]) return raw;
  const lower = raw.toLowerCase();
  if (lower === "zh" || lower === "zh-cn" || lower === "zh_hans") return "zh-CN";
  if (lower === "zh-tw" || lower === "zh-hk" || lower === "zh_hant") return "zh-TW";
  if (lower.startsWith("ja")) return "ja";
  if (lower.startsWith("ko")) return "ko";
  if (lower.startsWith("en")) return "en";
  return "en";
}

export function currentLang() {
  return normalizeLang(store.settings?.language || "en");
}

export function t(key, fallback = "", vars = null) {
  const lang = currentLang();
  // Empty string is a valid translation — do not fall through to the key.
  let value = DICT[lang]?.[key];
  if (value === undefined) value = DICT.en[key];
  if (value === undefined || value === null) value = fallback !== "" ? fallback : key;
  if (vars && typeof value === "string") {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replaceAll(`{${k}}`, String(v ?? ""));
    }
  }
  return value ?? key;
}

export function languageOptions() {
  return LOCALES.map((l) => ({
    value: l.value,
    label: t(`language.${l.value}`, l.native),
  }));
}

function setText(el, value) {
  if (!el) return;
  if (el.dataset.i18nAttr) {
    el.setAttribute(el.dataset.i18nAttr, value);
    return;
  }
  // keep child icons: only replace direct text or [data-i18n-text]
  const textNode = el.querySelector("[data-i18n-text]");
  if (textNode) {
    textNode.textContent = value;
    return;
  }
  // if element has only text / simple children without svg preference
  if (!el.querySelector("svg,img,input,kbd")) {
    el.textContent = value;
    return;
  }
  // find last text-bearing span without class ico
  const span = el.querySelector("span:not(.ico):not(.count):not(.chev)");
  if (span && !span.querySelector("svg")) {
    span.textContent = value;
    return;
  }
  el.setAttribute("aria-label", value);
}

export function applyLanguage() {
  const lang = currentLang();
  document.documentElement.lang = lang === "zh-CN" ? "zh-CN" : lang === "zh-TW" ? "zh-TW" : lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (!key) return;
    setText(el, t(key, el.dataset.i18nFallback || el.textContent));
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    el.setAttribute("placeholder", t(el.dataset.i18nPlaceholder, el.getAttribute("placeholder") || ""));
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    el.setAttribute("title", t(el.dataset.i18nTitle, el.getAttribute("title") || ""));
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    el.setAttribute("aria-label", t(el.dataset.i18nAria, el.getAttribute("aria-label") || ""));
  });
  // let dynamic views rebuild with t()
  document.dispatchEvent(new CustomEvent("codex:language-applied", { detail: { language: lang } }));
}
